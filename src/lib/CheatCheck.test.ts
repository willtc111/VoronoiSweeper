function retimeMoves(moves: MoveRecord[], speed: number): MoveRecord[] {
	let currentTime = moves[0].timestamp;
	return moves.map((move) => {
		currentTime += speed;
		return {
			...move,
			timestamp: currentTime,
		};
	});
}

